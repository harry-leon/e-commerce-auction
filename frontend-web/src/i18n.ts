export const translations = { en, vi }
export type TranslationKey = keyof typeof en

export function tr(lang: Lang, key: TranslationKey, replacements?: Record<string, string>): string {
    let text = translations[lang][key] || translations.en[key] || key
    if (replacements) {
        Object.entries(replacements).forEach(([k, v]) => {
            text = text.replace(`{${k}}`, v)
        })
    }
    return text
}

export function formatDate(dateStr: string, lang: Lang): string {
    const d = new Date(dateStr)
    if (lang === 'vi')
        return `${String(d.getDate()).padStart(2, '0')}/${String(d.getMonth() + 1).padStart(2, '0')}/${d.getFullYear()}`
    return `${String(d.getMonth() + 1).padStart(2, '0')}/${String(d.getDate()).padStart(2, '0')}/${d.getFullYear()}`
}

/** Hiển thị ngày và giờ theo ngôn ngữ giao diện cho khung thời gian đấu giá và lịch sử đặt giá. */
export function formatDateTime(dateStr: string, lang: Lang): string {
    const date = new Date(dateStr)
    return new Intl.DateTimeFormat(lang === 'vi' ? 'vi-VN' : 'en-US', {
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
        hour: '2-digit',
        minute: '2-digit',
    }).format(date)
}

/**
 * Định dạng số tiền theo tiền tệ hiển thị (VND cho 'vi', USD cho 'en').
 * Luồng: Kiểm tra tính hợp lệ của amount (chống lỗi runtime khi undefined/null/NaN) → format toLocaleString.
 */
export function formatCurrency(amount: number | undefined | null, lang: Lang): string {
    const safeAmount = typeof amount === 'number' && !isNaN(amount) ? amount : 0
    if (lang === 'vi')
        return safeAmount
            .toLocaleString('vi-VN', { style: 'currency', currency: 'VND' })
            .replace('₫', '$')
            .trim()
    return (
        '$' + safeAmount.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 })
    )
}

export function formatNumber(n: number, lang: Lang): string {
    if (lang === 'vi') return n.toLocaleString('vi-VN')
    return n.toLocaleString('en-US')
}
